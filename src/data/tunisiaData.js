/**
 * Returns exact or centroid coordinates for a Tunisian governorate and/or delegation
 */
export function getCoordinatesByLocation(city = '', delegation = '') {
  const norm = (s) => String(s || '').normalize('NFD').replace(/[\u0300-\u036f]/g, '').trim().toLowerCase();
  
  const cNorm = norm(city).replace(/^la\s+/, '');
  const dNorm = norm(delegation).replace(/^la\s+/, '');

  // 1. Try delegation match
  if (dNorm) {
    for (const [delName, coords] of Object.entries(TUNISIA_COORDINATES.delegations)) {
      const delNorm = norm(delName).replace(/^la\s+/, '');
      if (delNorm === dNorm || delNorm.includes(dNorm) || dNorm.includes(delNorm)) {
        return { lat: coords.lat, lng: coords.lng };
      }
    }
  }

  // 2. Try governorate match
  if (cNorm) {
    for (const [govName, coords] of Object.entries(TUNISIA_COORDINATES.governorates)) {
      const govNorm = norm(govName).replace(/^la\s+/, '');
      if (govNorm === cNorm || govNorm.includes(cNorm) || cNorm.includes(govNorm)) {
        return { lat: coords.lat, lng: coords.lng };
      }
    }
  }

  // Fallback: Tunis center
  return { lat: 36.8065, lng: 10.1815 };
}

/**
 * Robustly resolve doctor coordinates, detecting and preventing mismatched legacy defaults
 */
export function getDoctorCoordinates(doc) {
  if (!doc) return { lat: 36.8065, lng: 10.1815 };
  
  const latNum = parseFloat(doc.lat);
  const lngNum = parseFloat(doc.lng);
  
  const city = (doc.city || '').toLowerCase();
  const delegation = (doc.delegation || '').toLowerCase();
  const isArianaOrTunis = city.includes('ariana') || city.includes('tunis') || delegation.includes('ennasr');
  
  // Check if coordinates are the legacy Ariana default (approx 36.8742, 10.1583)
  const isLegacyArianaDefault = !isNaN(latNum) && !isNaN(lngNum) &&
    Math.abs(latNum - 36.8742) < 0.005 && Math.abs(lngNum - 10.1583) < 0.005;

  // If valid coordinates exist and are NOT an incongruous default for another city (like Kébili)
  if (!isNaN(latNum) && !isNaN(lngNum) && latNum > 30 && lngNum > 7 && (!isLegacyArianaDefault || isArianaOrTunis)) {
    return { lat: latNum, lng: lngNum };
  }

  // Resolve from governorate / delegation
  return getCoordinatesByLocation(doc.city, doc.delegation);
}

